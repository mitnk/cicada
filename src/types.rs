/// A heredoc body waiting in `Shell::heredocs` for its command to be built.
#[derive(Debug, Clone)]
pub struct Heredoc {
    pub body: String,
    /// The delimiter was quoted, so the body is literal.
    pub quoted: bool,
    /// A copy made for a single run (see `heredoc::apply_to_bodies`), dropped
    /// as soon as that run picks it up.
    pub transient: bool,
}

/// Prefix for marker tokens generated by the heredoc preprocessor. The real
/// heredoc body is stored in `Shell::heredocs` until the command is built.
pub const HEREDOC_MARKER_PREFIX: &str = "__cicada_heredoc_";

///
/// command line: `ls 'foo bar' 2>&1 > /dev/null < one-file` would be:
/// Command {
///     tokens: [("", "ls"), ("", "-G"), ("\'", "foo bar")],
///     redirects_to: [
///         ("2", ">", "&1"),
///         ("1", ">", "/dev/null"),
///     ],
///     redirect_from: Some(("<", "one-file")),
/// }
///
#[derive(Debug)]
pub struct Command {
    pub tokens: Tokens,
    pub redirects_to: Vec<Redirection>,
    pub redirect_from: Option<Token>,
    /// Body of the heredoc feeding this command's stdin, already expanded.
    pub heredoc: Option<String>,
}

#[derive(Debug)]
pub struct CommandLine {
    pub line: String,
    pub commands: Vec<Command>,
    pub envs: HashMap<String, String>,
    pub background: bool,
}

/// Is this token the operator `op` as written in the source?
///
/// A token only acts as an operator when it carries no quote marker: `cat '<'
/// f` passes `<` to `cat`, and a `<` that arrived from an expansion is data
/// too, because expansion marks such words (see `shell::SEP_GENERATED`).
fn is_op(token: &Token, op: &str) -> bool {
    token.0.is_empty() && token.1 == op
}

fn is_redirect_from_op(token: &Token) -> bool {
    is_op(token, "<") || is_op(token, "<<<")
}

/// Is this here-string operand a heredoc marker the preprocessor wrote?
///
/// Two things have to hold, and both are out of reach of a word that arrived
/// from an expansion: the name carries the session id (see
/// `heredoc::next_marker`), and the word is single quoted, which only the
/// source text can be -- an expanded value never brings a quote marker with
/// it. Without this, `cat <<< "$untrusted"` could be steered into reading the
/// body of some other heredoc in the same run.
fn is_heredoc_marker(sep: &str, value: &str) -> bool {
    sep == "'" && value.starts_with(HEREDOC_MARKER_PREFIX)
}

impl Command {
    pub fn from_tokens(tokens: Tokens, sh: &mut shell::Shell) -> Result<Command, String> {
        let mut tokens_new = tokens.clone();
        let mut redirects_from_type = String::new();
        let mut redirects_from_value = String::new();
        let mut heredoc = None;
        let mut has_redirect_from = tokens_new.iter().any(is_redirect_from_op);

        let mut len = tokens_new.len();
        while has_redirect_from {
            if let Some(idx) = tokens_new.iter().position(|x| is_op(x, "<")) {
                redirects_from_type = "<".to_string();
                tokens_new.remove(idx);
                len -= 1;
                if len > idx {
                    redirects_from_value = tokens_new.remove(idx).1;
                    len -= 1;
                }
            }
            if let Some(idx) = tokens_new.iter().position(|x| is_op(x, "<<<")) {
                redirects_from_type = "<<<".to_string();
                tokens_new.remove(idx);
                len -= 1;
                let mut value_sep = String::new();
                if len > idx {
                    let token = tokens_new.remove(idx);
                    value_sep = token.0;
                    redirects_from_value = token.1;
                    len -= 1;
                }
                if is_heredoc_marker(&value_sep, &redirects_from_value) {
                    // a here-string the heredoc preprocessor wrote: the body it
                    // stands for becomes this command's stdin. A word that only
                    // looks like a marker stays the here-string it is.
                    if let Some(body) =
                        crate::parsers::heredoc::take_body(sh, &redirects_from_value)
                    {
                        heredoc = Some(body);
                        redirects_from_type = String::new();
                        redirects_from_value = String::new();
                    }
                }
            }

            has_redirect_from = tokens_new.iter().any(is_redirect_from_op);
        }

        let tokens_final;
        let redirects_to;
        match tokens_to_redirections(&tokens_new) {
            Ok((_tokens, _redirects_to)) => {
                tokens_final = _tokens;
                redirects_to = _redirects_to;
            }
            Err(e) => {
                return Err(e);
            }
        }

        let redirect_from = if redirects_from_type.is_empty() {
            None
        } else {
            Some((redirects_from_type, redirects_from_value))
        };

        Ok(Command {
            tokens: tokens_final,
            redirects_to,
            redirect_from,
            heredoc,
        })
    }

    pub fn has_redirect_from(&self) -> bool {
        self.redirect_from.is_some() && self.redirect_from.clone().unwrap().0 == "<"
    }

    pub fn has_here_string(&self) -> bool {
        self.redirect_from.is_some() && self.redirect_from.clone().unwrap().0 == "<<<"
    }

    pub fn is_builtin(&self) -> bool {
        // a command can be all redirection and no word, as in `> foo` or a
        // heredoc with nothing in front of it -- there is no name to match
        !self.tokens.is_empty() && tools::is_builtin(&self.tokens[0].1)
    }
}

#[derive(Debug, Clone, Default)]
pub struct Job {
    pub cmd: String,
    pub id: i32,
    pub gid: i32,
    pub pids: Vec<i32>,
    pub pids_stopped: HashSet<i32>,
    pub status: String,
    pub is_bg: bool,
}

impl Job {
    pub fn all_members_stopped(&self) -> bool {
        for pid in &self.pids {
            if !self.pids_stopped.contains(pid) {
                return false;
            }
        }
        true
    }

    pub fn all_members_running(&self) -> bool {
        self.pids_stopped.is_empty()
    }
}

