fn split_tokens_by_pipes(tokens: &[Token]) -> Vec<Tokens> {
    let mut cmd = Vec::new();
    let mut cmds = Vec::new();
    for token in tokens {
        let sep = &token.0;
        let value = &token.1;
        if sep.is_empty() && value == "|" {
            if cmd.is_empty() {
                return Vec::new();
            }
            cmds.push(cmd.clone());
            cmd = Vec::new();
        } else {
            cmd.push(token.clone());
        }
    }
    if cmd.is_empty() {
        return Vec::new();
    }
    cmds.push(cmd.clone());
    cmds
}

pub(crate) fn drain_env_tokens(tokens: &mut Tokens) -> HashMap<String, String> {
    let mut envs: HashMap<String, String> = HashMap::new();
    let mut n = 0;
    // `(?s)` so that a value spanning a newline -- `A="one\ntwo"` -- is still
    // recognized as an assignment instead of being run as a command.
    let ptn_env = r"(?s)^([a-zA-Z0-9_]+)=(.*)$";
    let re = Regex::new(ptn_env).unwrap();
    for (sep, text) in tokens.iter() {
        // A word expansion marked as data (`shell::SEP_GENERATED`) is still an
        // assignment if that is how it was written: `B='x>y'; A=$B cmd` sets
        // `A` for `cmd`, it does not redirect.
        let sep_blocks = !sep.is_empty() && sep != shell::SEP_GENERATED;
        if sep_blocks || !libs::re::re_contains(text, ptn_env) {
            break;
        }

        for cap in re.captures_iter(text) {
            let name = cap[1].to_string();
            envs.insert(name, cap[2].to_string());
        }

        n += 1;
    }
    if n > 0 {
        tokens.drain(0..n);
    }
    envs
}

impl CommandLine {
    pub fn from_line(line: &str, sh: &mut shell::Shell) -> Result<CommandLine, String> {
        let linfo = parsers::parser_line::parse_line(line);
        let mut tokens = linfo.tokens;
        shell::do_expansion(sh, &mut tokens);
        let envs = drain_env_tokens(&mut tokens);

        let mut background = false;
        let len = tokens.len();
        if len > 1 && is_op(&tokens[len - 1], "&") {
            background = true;
            tokens.pop();
        }

        let mut commands = Vec::new();
        for sub_tokens in split_tokens_by_pipes(&tokens) {
            match Command::from_tokens(sub_tokens, sh) {
                Ok(c) => {
                    commands.push(c);
                }
                Err(e) => {
                    return Err(e);
                }
            }
        }

        Ok(CommandLine {
            line: line.to_string(),
            commands,
            envs,
            background,
        })
    }

    pub fn is_empty(&self) -> bool {
        self.commands.is_empty()
    }

    pub fn with_pipeline(&self) -> bool {
        self.commands.len() > 1
    }

    pub fn is_single_and_builtin(&self) -> bool {
        self.commands.len() == 1 && self.commands[0].is_builtin()
    }
}

#[cfg(test)]
mod tests {
    use super::is_heredoc_marker;
    use super::HEREDOC_MARKER_PREFIX;

    #[test]
    fn test_only_the_preprocessors_own_marker_is_honored() {
        let marker = format!("{}9f2c4b_0", HEREDOC_MARKER_PREFIX);

        // as the preprocessor writes it
        assert!(is_heredoc_marker("'", &marker));

        // a value that arrived from an expansion never carries a quote
        // marker, so `cat <<< "$untrusted"` cannot reach a heredoc body
        assert!(!is_heredoc_marker("", &marker));
        assert!(!is_heredoc_marker("\"", &marker));
        assert!(!is_heredoc_marker("`", &marker));

        // an ordinary here-string stays one
        assert!(!is_heredoc_marker("'", "some text"));
    }
}
